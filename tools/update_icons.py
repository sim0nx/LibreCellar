#!/usr/bin/env python3
"""Regenerate the app's icons from tools/icons.txt.

For every line "<symbol> <filled|outline>" it downloads the Material Symbols Rounded icon
(weight 400, 24dp) as an Android vector drawable from Google Fonts, writes it to
app/src/main/res/drawable/ic_<symbol>[_outline].xml, deletes drawables of icons no longer
listed, and regenerates app/src/main/java/org/librecellar/ui/theme/AppIcons.kt.

Usage: python3 tools/update_icons.py   (standard library only)
"""

import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICON_LIST = ROOT / "tools" / "icons.txt"
DRAWABLES = ROOT / "app/src/main/res/drawable"
APP_ICONS = ROOT / "app/src/main/java/org/librecellar/ui/theme/AppIcons.kt"

URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{symbol}/{variant}/24px.xml"
# Marks generated drawables, so stale ones can be removed without touching other files
MARKER = "<!-- Material Symbols Rounded"

APP_ICONS_HEADER = '''package org.librecellar.ui.theme

import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.res.vectorResource
import org.librecellar.R

// Generated by tools/update_icons.py from tools/icons.txt; do not edit by hand.

/**
 * The app's icons: Material Symbols (Rounded, weight 400) as vector drawables in res/drawable,
 * from https://fonts.google.com/icons. Filled icons are named after the symbol, outline ones
 * end in "Outline". To add one, list it in tools/icons.txt and run tools/update_icons.py.
 */
object AppIcons {
'''


def read_icon_list() -> list[tuple[str, str]]:
    icons = []
    for number, line in enumerate(ICON_LIST.read_text().splitlines(), start=1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2 or parts[1] not in ("filled", "outline") or not re.fullmatch(r"[a-z0-9_]+", parts[0]):
            sys.exit(f"{ICON_LIST.name}:{number}: expected '<symbol> <filled|outline>', got: {line}")
        icons.append((parts[0], parts[1]))
    if len(set(icons)) != len(icons):
        sys.exit(f"{ICON_LIST.name}: duplicate entries")
    return sorted(icons)


def download(symbol: str, style: str) -> str:
    url = URL.format(symbol=symbol, variant="fill1" if style == "filled" else "default")
    for attempt in range(3):
        try:
            with urllib.request.urlopen(url, timeout=20) as response:
                xml = response.read().decode()
            break
        except urllib.error.HTTPError as e:
            if e.code == 404:
                sys.exit(f"Unknown icon '{symbol}' (check the name on fonts.google.com/icons)")
            error = e
        except OSError as e:
            error = e
        time.sleep(1 + attempt)
    else:
        sys.exit(f"Download failed for '{symbol}': {error}")
    if not xml.lstrip().startswith("<vector"):
        sys.exit(f"Unexpected content for '{symbol}'")
    # Compose's Icon applies its own tint; the theme attribute is not needed
    xml = xml.replace('\n    android:tint="?attr/colorControlNormal"', "")
    return f'{MARKER} "{symbol}" ({style}, weight 400, 24dp), Apache License 2.0 -->\n{xml}'


def names(symbol: str, style: str) -> tuple[str, str]:
    suffix = "_outline" if style == "outline" else ""
    prop = "".join(part.capitalize() for part in symbol.split("_")) + ("Outline" if suffix else "")
    return f"ic_{symbol}{suffix}", prop


def main() -> None:
    icons = read_icon_list()
    DRAWABLES.mkdir(parents=True, exist_ok=True)
    wanted = set()
    for symbol, style in icons:
        file, _ = names(symbol, style)
        wanted.add(f"{file}.xml")
        (DRAWABLES / f"{file}.xml").write_text(download(symbol, style))

    removed = []
    for path in DRAWABLES.glob("ic_*.xml"):
        if path.name not in wanted and path.read_text().startswith(MARKER):
            path.unlink()
            removed.append(path.name)

    properties = "".join(
        f"    val {prop}: ImageVector @Composable get() = ImageVector.vectorResource(R.drawable.{file})\n"
        for file, prop in (names(symbol, style) for symbol, style in icons)
    )
    APP_ICONS.write_text(APP_ICONS_HEADER + properties + "}\n")

    print(f"{len(icons)} icons written" + (f", removed: {', '.join(sorted(removed))}" if removed else ""))


if __name__ == "__main__":
    main()
